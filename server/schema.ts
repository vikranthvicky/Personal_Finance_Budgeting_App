export const relationalSchema = [
  `CREATE TABLE IF NOT EXISTS budgets (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    budget_month CHAR(7) NOT NULL DEFAULT '1970-01',
    current_balance DECIMAL(14,2) NULL,
    revision INT NOT NULL DEFAULT 1,
    state_json LONGTEXT NOT NULL,
    created_at VARCHAR(32) NOT NULL,
    updated_at VARCHAR(32) NOT NULL
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS categories (
    budget_id VARCHAR(64) NOT NULL,
    id VARCHAR(64) NOT NULL,
    name VARCHAR(120) NOT NULL,
    color VARCHAR(20) NOT NULL,
    icon VARCHAR(40) NOT NULL,
    planned DECIMAL(14,2) NOT NULL,
    rollover ENUM('carry','reset','cap') NOT NULL,
    rollover_cap DECIMAL(14,2) NULL,
    PRIMARY KEY (budget_id, id),
    CONSTRAINT fk_categories_budget FOREIGN KEY (budget_id) REFERENCES budgets(id) ON DELETE CASCADE
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS budget_envelopes (
    budget_id VARCHAR(64) NOT NULL,
    category_id VARCHAR(64) NOT NULL,
    budget_month CHAR(7) NOT NULL,
    planned DECIMAL(14,2) NOT NULL,
    rollover ENUM('carry','reset','cap') NOT NULL,
    rollover_cap DECIMAL(14,2) NULL,
    PRIMARY KEY (budget_id, category_id, budget_month),
    CONSTRAINT fk_envelopes_category FOREIGN KEY (budget_id, category_id) REFERENCES categories(budget_id, id) ON DELETE CASCADE
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS income_sources (
    budget_id VARCHAR(64) NOT NULL,
    id VARCHAR(64) NOT NULL,
    name VARCHAR(120) NOT NULL,
    amount DECIMAL(14,2) NOT NULL,
    cadence VARCHAR(120) NOT NULL,
    frequency VARCHAR(24) NULL,
    start_date DATE NULL,
    day TINYINT UNSIGNED NULL,
    second_day TINYINT UNSIGNED NULL,
    interval_days INT UNSIGNED NULL,
    weekday TINYINT UNSIGNED NULL,
    week_ordinal TINYINT NULL,
    PRIMARY KEY (budget_id, id),
    CONSTRAINT fk_income_budget FOREIGN KEY (budget_id) REFERENCES budgets(id) ON DELETE CASCADE
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS transactions (
    budget_id VARCHAR(64) NOT NULL,
    id VARCHAR(128) NOT NULL,
    transaction_date DATE NOT NULL,
    merchant VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    amount DECIMAL(14,2) NOT NULL,
    category_id VARCHAR(64) NOT NULL,
    account VARCHAR(120) NULL,
    notes TEXT NULL,
    scheduled_occurrence_id VARCHAR(160) NULL,
    reimbursable BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE KEY uq_transaction_occurrence (budget_id, scheduled_occurrence_id),
    PRIMARY KEY (budget_id, id),
    KEY ix_transactions_date (budget_id, transaction_date),
    KEY ix_transactions_category (budget_id, category_id),
    CONSTRAINT fk_transactions_budget FOREIGN KEY (budget_id) REFERENCES budgets(id) ON DELETE CASCADE,
    CONSTRAINT fk_transactions_category FOREIGN KEY (budget_id, category_id) REFERENCES categories(budget_id, id)
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS transaction_splits (
    budget_id VARCHAR(64) NOT NULL,
    id VARCHAR(64) NOT NULL,
    transaction_id VARCHAR(128) NOT NULL,
    category_id VARCHAR(64) NOT NULL,
    amount DECIMAL(14,2) NOT NULL,
    PRIMARY KEY (budget_id, id),
    CONSTRAINT fk_splits_transaction FOREIGN KEY (budget_id, transaction_id) REFERENCES transactions(budget_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_splits_category FOREIGN KEY (budget_id, category_id) REFERENCES categories(budget_id, id)
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS recurring_rules (
    budget_id VARCHAR(64) NOT NULL,
    id VARCHAR(64) NOT NULL,
    name VARCHAR(160) NOT NULL,
    amount DECIMAL(14,2) NOT NULL,
    category_id VARCHAR(64) NOT NULL,
    cadence ENUM('weekly','biweekly','semimonthly','monthly','monthly-weekday','quarterly','yearly','custom') NOT NULL,
    day TINYINT UNSIGNED NOT NULL,
    second_day TINYINT UNSIGNED NULL,
    interval_days INT UNSIGNED NULL,
    weekday TINYINT UNSIGNED NULL,
    week_ordinal TINYINT NULL,
    next_date DATE NOT NULL,
    kind ENUM('bill','subscription','sinking') NOT NULL,
    active BOOLEAN NOT NULL,
    PRIMARY KEY (budget_id, id),
    CONSTRAINT fk_recurring_budget FOREIGN KEY (budget_id) REFERENCES budgets(id) ON DELETE CASCADE,
    CONSTRAINT fk_recurring_category FOREIGN KEY (budget_id, category_id) REFERENCES categories(budget_id, id)
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS scheduled_occurrences (
    budget_id VARCHAR(64) NOT NULL,
    occurrence_id VARCHAR(160) NOT NULL,
    recurring_id VARCHAR(64) NULL,
    scheduled_date DATE NOT NULL,
    status ENUM('scheduled','posted') NOT NULL,
    transaction_id VARCHAR(128) NULL,
    PRIMARY KEY (budget_id, occurrence_id),
    UNIQUE KEY uq_occurrence_transaction (budget_id, transaction_id),
    CONSTRAINT fk_occurrence_budget FOREIGN KEY (budget_id) REFERENCES budgets(id) ON DELETE CASCADE,
    CONSTRAINT fk_occurrence_rule FOREIGN KEY (budget_id, recurring_id) REFERENCES recurring_rules(budget_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_occurrence_transaction FOREIGN KEY (budget_id, transaction_id) REFERENCES transactions(budget_id, id) ON DELETE CASCADE
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS reimbursements (
    budget_id VARCHAR(64) NOT NULL,
    transaction_id VARCHAR(128) NOT NULL,
    expected_amount DECIMAL(14,2) NOT NULL,
    received_legacy_amount DECIMAL(14,2) NULL,
    status ENUM('pending','received') NOT NULL,
    has_receipt_list BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (budget_id, transaction_id),
    CONSTRAINT fk_reimbursement_transaction FOREIGN KEY (budget_id, transaction_id) REFERENCES transactions(budget_id, id) ON DELETE CASCADE
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS reimbursement_receipts (
    budget_id VARCHAR(64) NOT NULL,
    id VARCHAR(128) NOT NULL,
    transaction_id VARCHAR(128) NOT NULL,
    received_date DATE NOT NULL,
    amount DECIMAL(14,2) NOT NULL,
    note TEXT NULL,
    PRIMARY KEY (budget_id, id),
    CONSTRAINT fk_receipt_reimbursement FOREIGN KEY (budget_id, transaction_id) REFERENCES reimbursements(budget_id, transaction_id) ON DELETE CASCADE
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS fund_transfers (
    budget_id VARCHAR(64) NOT NULL,
    id VARCHAR(64) NOT NULL,
    transfer_date DATE NOT NULL,
    from_category_id VARCHAR(64) NOT NULL,
    to_category_id VARCHAR(64) NOT NULL,
    amount DECIMAL(14,2) NOT NULL,
    note TEXT NOT NULL,
    PRIMARY KEY (budget_id, id),
    CONSTRAINT fk_transfer_budget FOREIGN KEY (budget_id) REFERENCES budgets(id) ON DELETE CASCADE,
    CONSTRAINT fk_transfer_from FOREIGN KEY (budget_id, from_category_id) REFERENCES categories(budget_id, id),
    CONSTRAINT fk_transfer_to FOREIGN KEY (budget_id, to_category_id) REFERENCES categories(budget_id, id)
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS category_adjustments (
    budget_id VARCHAR(64) NOT NULL,
    id VARCHAR(64) NOT NULL,
    adjustment_date DATE NOT NULL,
    category_id VARCHAR(64) NOT NULL,
    amount DECIMAL(14,2) NOT NULL,
    note TEXT NOT NULL,
    PRIMARY KEY (budget_id, id),
    CONSTRAINT fk_adjustment_budget FOREIGN KEY (budget_id) REFERENCES budgets(id) ON DELETE CASCADE,
    CONSTRAINT fk_adjustment_category FOREIGN KEY (budget_id, category_id) REFERENCES categories(budget_id, id)
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS audit_logs (
    budget_id VARCHAR(64) NOT NULL,
    id VARCHAR(128) NOT NULL,
    at VARCHAR(32) NOT NULL,
    message TEXT NOT NULL,
    PRIMARY KEY (budget_id, id),
    CONSTRAINT fk_audit_budget FOREIGN KEY (budget_id) REFERENCES budgets(id) ON DELETE CASCADE
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS category_rules (
    budget_id VARCHAR(64) NOT NULL,
    id VARCHAR(64) NOT NULL,
    contains_phrase VARCHAR(255) NOT NULL,
    category_id VARCHAR(64) NOT NULL,
    PRIMARY KEY (budget_id, id),
    CONSTRAINT fk_rule_budget FOREIGN KEY (budget_id) REFERENCES budgets(id) ON DELETE CASCADE,
    CONSTRAINT fk_rule_category FOREIGN KEY (budget_id, category_id) REFERENCES categories(budget_id, id)
  ) ENGINE=InnoDB`,
  `CREATE TABLE IF NOT EXISTS relational_migrations (
    budget_id VARCHAR(64) PRIMARY KEY,
    migrated_at VARCHAR(32) NOT NULL,
    source_revision INT NOT NULL,
    CONSTRAINT fk_migration_budget FOREIGN KEY (budget_id) REFERENCES budgets(id) ON DELETE CASCADE
  ) ENGINE=InnoDB`,
] as const
